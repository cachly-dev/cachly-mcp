import { describe, it, expect } from 'vitest';
import { frageAusPrompt } from '../prompt-herkunft.js';

// Wortlaut wie im Claude-Code-Protokoll vom 18.11.2026 (Pfad gekuerzt).
const MELDUNG = [
  '<task-notification>',
  '<task-id>biqjh9p72</task-id>',
  '<tool-use-id>toolu_01ANFZk7EAbxSsWvSC8oGajA</tool-use-id>',
  '<output-file>C:\\Users\\x\\tasks\\biqjh9p72.output</output-file>',
  '<status>completed</status>',
  '<summary>Background command "Wait for the paid lever runner to finish" completed (exit code 0)</summary>',
  '</task-notification>',
].join('\n');

describe('frageAusPrompt', () => {
  it('eine reine Hintergrundmeldung ergibt keine Frage', () => {
    expect(frageAusPrompt(MELDUNG)).toBe('');
    expect(frageAusPrompt(`  \n${MELDUNG}\n  `)).toBe('');
  });

  it('zwei Meldungen hintereinander ergeben ebenfalls keine Frage', () => {
    expect(frageAusPrompt(`${MELDUNG}\n${MELDUNG}`)).toBe('');
  });

  it('getippter Text neben einer Meldung bleibt die Frage', () => {
    expect(frageAusPrompt(`${MELDUNG}\nwarum schlaegt der deploy fehl?`)).toBe('warum schlaegt der deploy fehl?');
  });

  it('Ausgabe lokaler Befehle und Systemhinweise fallen weg', () => {
    expect(frageAusPrompt('<local-command-stdout>Total cost: $0.12</local-command-stdout>')).toBe('');
    expect(frageAusPrompt('<local-command-caveat>Caveat: generated by the user</local-command-caveat>')).toBe('');
    expect(frageAusPrompt('<system-reminder>todo list is empty</system-reminder> fix the login loop')).toBe('fix the login loop');
  });

  it('Schraegstrich-Befehle bleiben stehen: die Argumente beschreiben die Aufgabe', () => {
    const p = '<command-name>/review</command-name>\n<command-args>auth redirect loop</command-args>';
    expect(frageAusPrompt(p)).toBe(p);
  });

  it('ein Tag ohne Gegenstueck ist Text ueber das Markup und bleibt', () => {
    const p = 'warum loest <task-notification> eine Einblendung aus?';
    expect(frageAusPrompt(p)).toBe(p);
  });

  it('normale Eingaben bleiben unveraendert (nur getrimmt)', () => {
    expect(frageAusPrompt('  Wo laeuft Whisper?  ')).toBe('Wo laeuft Whisper?');
    expect(frageAusPrompt('')).toBe('');
  });
});
